const LangCtx = createContext({ lang: 'ar', t: dict.ar, toggle: () => {} });

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('ast_lang') || 'ar');
  useEffect(() => {
    localStorage.setItem('ast_lang', lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  }, [lang]);
  const value = useMemo(
    () => ({ lang, t: dict[lang], toggle: () => setLang((l) => (l === 'ar' ? 'en' : 'ar')) }),
    [lang],
  );
  return <LangCtx.Provider value={value}>{children}</LangCtx.Provider>;
}

export const useLang = () => useContext(LangCtx);
